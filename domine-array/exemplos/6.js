// 6. reverse() – Invertendo
// Inverte a ordem dos itens.
// ⚠️ ATENÇÃO: reverse() altera o array original!

console.log('=== 6. reverse() ===');

// Exemplo 1 – números
const numeros = [1, 2, 3, 4, 5];
numeros.reverse();
console.log('Números invertidos:', numeros); // [5, 4, 3, 2, 1]

// Exemplo 2 – ranking
const ranking = ['João', 'Maria', 'Carlos', 'Ana'];

ranking.reverse();
console.log('Ranking invertido:', ranking); // ["Ana", "Carlos", "Maria", "João"]
